CREATE TABLE "Estudiante" (
    "id_estudiante" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "codigo_sie_cee" VARCHAR(50) NOT NULL,
    "apellido_paterno" VARCHAR(100) NOT NULL,
    "apellido_materno" VARCHAR(100),
    "nombre1" VARCHAR(100) NOT NULL,
    "nombre2" VARCHAR(100),
    "pais_nacimiento" VARCHAR(100) NOT NULL,
    "departamento_nacimiento" VARCHAR(100) NOT NULL,
    "provincia_nacimiento" VARCHAR(100) NOT NULL,
    "localidad_nacimiento" VARCHAR(100) NOT NULL,
    "tipo_documento" VARCHAR(50) NOT NULL,
    "numero_documento" VARCHAR(50) NOT NULL,
    "complemento_documento" VARCHAR(20),
    "lugar_expedicion_documento" VARCHAR(100),
    "fecha_nacimiento" DATE NOT NULL,
    "sexo" VARCHAR(30) NOT NULL,
    "tiene_certificado_nacimiento" BOOLEAN NOT NULL DEFAULT FALSE,
    "certificado_oficialia" VARCHAR(100),
    "certificado_libro" VARCHAR(50),
    "certificado_partida" VARCHAR(50),
    "certificado_folio" VARCHAR(50),

    CONSTRAINT "pk_estudiante"
        PRIMARY KEY ("id_estudiante"),

    CONSTRAINT "uq_estudiante_sie"
        UNIQUE ("codigo_sie_cee"),

    CONSTRAINT "ck_estudiante_sie_no_vacio"
        CHECK (BTRIM("codigo_sie_cee") <> ''),

    CONSTRAINT "ck_estudiante_documento_no_vacio"
        CHECK (
            BTRIM("tipo_documento") <> ''
            AND BTRIM("numero_documento") <> ''
        ),

    CONSTRAINT "ck_estudiante_nombres_no_vacios"
        CHECK (
            BTRIM("apellido_paterno") <> ''
            AND BTRIM("nombre1") <> ''
            AND BTRIM("pais_nacimiento") <> ''
            AND BTRIM("departamento_nacimiento") <> ''
            AND BTRIM("provincia_nacimiento") <> ''
            AND BTRIM("localidad_nacimiento") <> ''
        ),

    CONSTRAINT "ck_estudiante_sexo_no_vacio"
        CHECK (BTRIM("sexo") <> ''),


    CONSTRAINT "ck_estudiante_complemento_no_vacio"
        CHECK (
            "complemento_documento" IS NULL
            OR BTRIM("complemento_documento") <> ''
        ),

    CONSTRAINT "ck_estudiante_certificado"
        CHECK (
            (
                "tiene_certificado_nacimiento" = FALSE
                AND "certificado_oficialia" IS NULL
                AND "certificado_libro" IS NULL
                AND "certificado_partida" IS NULL
                AND "certificado_folio" IS NULL
            )
            OR
            (
                "tiene_certificado_nacimiento" = TRUE
                AND "certificado_oficialia" IS NOT NULL
                AND BTRIM("certificado_oficialia") <> ''
                AND "certificado_libro" IS NOT NULL
                AND BTRIM("certificado_libro") <> ''
                AND "certificado_partida" IS NOT NULL
                AND BTRIM("certificado_partida") <> ''
                AND "certificado_folio" IS NOT NULL
                AND BTRIM("certificado_folio") <> ''
            )
        )
);

