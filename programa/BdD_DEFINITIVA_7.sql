-- "Otro" debe tener una especificación; los demás servicios no deben
-- guardar texto en especificar_otro.
CREATE OR REPLACE FUNCTION "fn_validar_especificar_otro_servicio"()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_nombre_servicio VARCHAR(150);
BEGIN
    SELECT "nombre_servicio"
      INTO v_nombre_servicio
      FROM "Servicio_Multidisciplinario"
     WHERE "id_servicio" = NEW."id_servicio";

    IF v_nombre_servicio IS NULL THEN
        RAISE EXCEPTION
            'El servicio % no existe.',
            NEW."id_servicio";
    END IF;

    IF LOWER(BTRIM(v_nombre_servicio)) = 'otro' THEN
        IF NULLIF(BTRIM(NEW."especificar_otro"), '') IS NULL THEN
            RAISE EXCEPTION
                'Debe especificar el servicio cuando se selecciona "Otro".';
        END IF;
    ELSE
        IF NULLIF(BTRIM(NEW."especificar_otro"), '') IS NOT NULL THEN
            RAISE EXCEPTION
                'especificar_otro solo puede utilizarse con el servicio "Otro".';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

