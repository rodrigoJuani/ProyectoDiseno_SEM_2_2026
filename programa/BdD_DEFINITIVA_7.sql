-- Si familiar_con_ discapacidad = FALSE, no se permite registrar
-- familiares en familiar_discapacidad. Si es TRUE, debe existir al
-- menos un registro al finalizar la transaccion.
CREATE OR REPLACE FUNCTION "fn_validar_familiar_discapacidad_insert"()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_tiene BOOLEAN;
BEGIN
    -- El trigger se dispara sobre familiar_discapacidad, cuyo registro NO
    -- tiene "id_familia"; se resuelve a traves de Estudiante_Familia.
    SELECT gf."familiar_con_ discapacidad"
      INTO v_tiene
      FROM "Estudiante_Familia" ef
      JOIN "Grupo_Familiar" gf
        ON gf."id_familia" = ef."id_familia"
     WHERE ef."id_familiar" = NEW."id_familiar";

    IF NOT FOUND OR v_tiene IS NULL THEN
        RAISE EXCEPTION 'La familia del familiar % no existe.', NEW."id_familiar";
    END IF;

    IF v_tiene = FALSE THEN
        RAISE EXCEPTION 'No se puede llenar familiar_discapacidad cuando familiar_con_ discapacidad = FALSE.';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "trg_familiar_discapacidad_bandera"
BEFORE INSERT OR UPDATE OF "id_familiar"
ON "familiar_discapacidad"
FOR EACH ROW
EXECUTE FUNCTION "fn_validar_familiar_discapacidad_insert"();

CREATE OR REPLACE FUNCTION "fn_validar_grupo_familiar_discapacidad_final"()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_id_familia BIGINT;
    v_id_familiar BIGINT;
    v_tiene BOOLEAN;
    v_cantidad BIGINT;
BEGIN
    -- La funcion se comparte entre dos tablas con columnas distintas:
    --   * Grupo_Familiar       -> el registro SI tiene "id_familia"
    --   * familiar_discapacidad-> NO tiene "id_familia"; se resuelve via Estudiante_Familia
    IF TG_TABLE_NAME = 'familiar_discapacidad' THEN
        IF TG_OP = 'DELETE' THEN
            v_id_familiar := OLD."id_familiar";
        ELSE
            v_id_familiar := NEW."id_familiar";
        END IF;

        SELECT ef."id_familia"
          INTO v_id_familia
          FROM "Estudiante_Familia" ef
         WHERE ef."id_familiar" = v_id_familiar;
    ELSE
        v_id_familia := COALESCE(NEW."id_familia", OLD."id_familia");
    END IF;

    -- Si el familiar o la familia ya fueron eliminados (borrado en cascada),
    -- no hay nada que validar.
    IF v_id_familia IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT "familiar_con_ discapacidad"
      INTO v_tiene
      FROM "Grupo_Familiar"
     WHERE "id_familia" = v_id_familia;

    IF v_tiene IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT COUNT(*)
      INTO v_cantidad
      FROM "familiar_discapacidad" fd
      JOIN "Estudiante_Familia" ef
        ON ef."id_familiar" = fd."id_familiar"
     WHERE ef."id_familia" = v_id_familia;

    IF v_tiene = TRUE AND v_cantidad = 0 THEN
        RAISE EXCEPTION 'La familia % indica familiar con discapacidad, pero no existe registro en familiar_discapacidad.', v_id_familia;
    ELSIF v_tiene = FALSE AND v_cantidad > 0 THEN
        RAISE EXCEPTION 'La familia % no indica familiar con discapacidad, pero existen registros en familiar_discapacidad.', v_id_familia;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE CONSTRAINT TRIGGER "trg_grupo_familiar_discapacidad_final"
AFTER INSERT OR UPDATE OF "familiar_con_ discapacidad"
ON "Grupo_Familiar"
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION "fn_validar_grupo_familiar_discapacidad_final"();

CREATE CONSTRAINT TRIGGER "trg_familiar_discapacidad_final"
AFTER INSERT OR UPDATE OR DELETE
ON "familiar_discapacidad"
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW
EXECUTE FUNCTION "fn_validar_grupo_familiar_discapacidad_final"();

