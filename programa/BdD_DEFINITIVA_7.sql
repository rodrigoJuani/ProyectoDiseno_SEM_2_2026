-- PostgreSQL no debe usar CURRENT_DATE directamente en CHECK:
-- la fecha actual cambia con el tiempo y el CHECK se evalúa al
-- insertar/actualizar, no de forma continua. Se valida mediante trigger.

CREATE OR REPLACE FUNCTION "fn_validar_fecha_nacimiento_no_futura"()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW."fecha_nacimiento" IS NOT NULL
       AND NEW."fecha_nacimiento" > CURRENT_DATE THEN
        RAISE EXCEPTION
            'La fecha de nacimiento no puede ser futura: %',
            NEW."fecha_nacimiento";
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "trg_estudiante_fecha_nacimiento"
BEFORE INSERT OR UPDATE OF "fecha_nacimiento"
ON "Estudiante"
FOR EACH ROW
EXECUTE FUNCTION "fn_validar_fecha_nacimiento_no_futura"();

CREATE TRIGGER "trg_tutor_fecha_nacimiento"
BEFORE INSERT OR UPDATE OF "fecha_nacimiento"
ON "Padre_Madre_Tutor"
FOR EACH ROW
EXECUTE FUNCTION "fn_validar_fecha_nacimiento_no_futura"();

